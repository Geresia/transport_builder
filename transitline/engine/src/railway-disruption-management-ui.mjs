// B14-M14: read engine-created railway disruptions and let the player choose one engine-priced
// recovery response. Hazards, duration, resolution and money remain ScenarioRuntime concerns.

const ongoing = (event) => event?.status === "active" || event?.status === "responding";
const key = (value) => String(value);
const clone = (value) => structuredClone(value);
const yen = new Intl.NumberFormat("ja-JP", { style: "currency", currency: "JPY", maximumFractionDigits: 0 });

export function buildRailwayDisruptionManagementView({ report = null, responsesFor = () => [] } = {}) {
  const events = Array.isArray(report?.events) ? report.events : [];
  return events.map((event) => ({
    id: key(event.id), kind: event.kind, status: event.status, lineId: event.lineId ?? null,
    trackSegmentId: event.trackSegmentId ?? null, blockId: event.blockId ?? null, trainId: event.trainId ?? null,
    effect: clone(event.effect ?? null), expectedEndMinute: Number.isFinite(event.expectedEndMinute) ? event.expectedEndMinute : null,
    response: clone(event.response ?? null),
    // Only an active event may receive a response. The engine remains the final boundary.
    responseOptions: event.status === "active" ? clone(responsesFor(event) ?? []) : [],
  }));
}

const node = (doc, tag, props = {}, ...children) => {
  const element = doc.createElement(tag);
  Object.assign(element, props);
  element.append(...children);
  if ("value" in props) element.value = props.value;
  return element;
};
const text = (doc, tag, className, value) => node(doc, tag, { className, textContent: value });
const message = (error) => error instanceof Error ? error.message : String(error);
const effectText = (effect) => effect?.closed === true ? "closed" : Number.isFinite(effect?.speedLimitMps) ? `speed limit ${effect.speedLimitMps} m/s` : "effect unknown";

export function mountRailwayDisruptionManagementPanel({ container, runtime, onChange = () => {} } = {}) {
  if (!container) throw new Error("A railway disruption management container is required");
  for (const method of ["railwayDisruptionReport", "railwayDisruptionResponseOptions", "respondRailwayDisruption"]) {
    if (typeof runtime?.[method] !== "function") throw new Error(`A ScenarioRuntime with ${method} is required`);
  }
  const doc = container.ownerDocument ?? document;
  let fingerprint = null;
  let error = null;

  function viewNow() {
    const report = runtime.railwayDisruptionReport();
    return buildRailwayDisruptionManagementView({ report, responsesFor: (event) => runtime.railwayDisruptionResponseOptions(event.id) });
  }

  function refresh({ force = false } = {}) {
    const view = viewNow();
    const next = JSON.stringify(view);
    if (!force && next === fingerprint) return;
    fingerprint = next;
    const active = view.filter(ongoing);
    const children = [text(doc, "p", "railway-disruption-notice", "Rail incidents are generated by the simulation. Choose a recovery response; duration, cost, reputation and recovery are determined by the engine.")];
    if (!view.length) children.push(text(doc, "p", "railway-disruption-empty", "No railway disruptions have occurred."));
    for (const event of view) {
      const card = node(doc, "article", { className: `railway-disruption-card ${event.status}` },
        text(doc, "strong", "", `${event.kind} · ${event.id}`),
        text(doc, "div", "railway-disruption-facts", `line ${event.lineId ?? "unknown"} · track ${event.trackSegmentId ?? "unknown"} · ${effectText(event.effect)}`),
        text(doc, "div", "railway-disruption-facts", `expected end ${event.expectedEndMinute ?? "unknown"} · ${event.status}`));
      if (event.response) card.append(text(doc, "div", "railway-disruption-response", `${event.response.label ?? event.response.responseId} · ${yen.format(event.response.directCostJPY ?? 0)} · remaining ${event.response.revisedRemainingMinutes ?? "unknown"} min`));
      if (event.status === "active") {
        const select = node(doc, "select", { value: "" }, node(doc, "option", { value: "", textContent: "Select recovery response" }), ...event.responseOptions.map((option) => node(doc, "option", { value: option.id, textContent: `${option.label} · ${yen.format(option.directCostJPY)}` })));
        const apply = node(doc, "button", { type: "button", textContent: "Commit recovery response", disabled: !event.responseOptions.length });
        select.addEventListener("change", () => { apply.disabled = !select.value; });
        apply.addEventListener("click", () => {
          if (!select.value) return;
          try {
            runtime.respondRailwayDisruption(event.id, select.value);
            error = null;
            fingerprint = null;
            onChange();
          } catch (cause) { error = message(cause); fingerprint = null; }
          refresh({ force: true });
        });
        card.append(select, apply);
      }
      children.push(card);
    }
    if (error) children.push(text(doc, "div", "railway-disruption-error", error));
    children.push(text(doc, "div", "railway-disruption-count", `${active.length} ongoing`));
    container.replaceChildren(...children);
  }

  refresh({ force: true });
  return { refresh };
}
